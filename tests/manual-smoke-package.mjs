import fs from "node:fs/promises";
import path from "node:path";
import { validatePdf } from "./helpers/pdf-engine-test-utils.mjs";

const root = process.cwd();
const sourceDir = path.join(root, "tmp", "corpus-manifest-smoke", "surrogate-pdfs");
const packageDir = path.join(root, "tmp", "manual-compatibility-package");
const manifestPath = path.join(packageDir, "manifest.json");
const checklistPath = path.join(packageDir, "manual-smoke-checklist.md");
const minimumCount = 50;
const viewers = ["Acrobat Pro/Reader", "macOS Preview", "Google Chrome", "Microsoft Edge"];

const sourceFiles = (await fs.readdir(sourceDir).catch(() => []))
  .filter((file) => file.endsWith(".pdf"))
  .sort();

if (sourceFiles.length < minimumCount) {
  throw new Error(
    `manual smoke package needs ${minimumCount} generated surrogate PDFs; found ${sourceFiles.length}. Run npm run test:corpus first.`,
  );
}

await fs.rm(packageDir, { force: true, recursive: true });
await fs.mkdir(packageDir, { recursive: true });

const selected = selectRepresentativeFiles(sourceFiles, minimumCount);
const entries = [];
for (const [index, sourceFile] of selected.entries()) {
  const sourcePath = path.join(sourceDir, sourceFile);
  const targetFile = `${String(index + 1).padStart(2, "0")}-${sourceFile}`;
  const targetPath = path.join(packageDir, targetFile);
  await fs.copyFile(sourcePath, targetPath);
  const validation = await validatePdf(targetPath);
  if (!validation.ok || !validation.qpdfChecked) {
    throw new Error(`manual package PDF failed validation ${targetFile}: ${JSON.stringify(validation)}`);
  }
  entries.push({
    id: `MANUAL-${String(index + 1).padStart(3, "0")}`,
    file: targetFile,
    category: extractCategory(sourceFile),
    path: targetPath,
    pageCount: validation.pageCount,
    textLength: validation.textLength,
    qpdfChecked: validation.qpdfChecked,
    viewers: Object.fromEntries(viewers.map((viewer) => [viewer, "Pending"])),
  });
}

await fs.writeFile(
  manifestPath,
  JSON.stringify(
    {
      ok: true,
      generatedAt: new Date().toISOString(),
      purpose:
        "Stable package for manual Acrobat/Preview/Chrome/Edge smoke. Pending entries are not compatibility pass evidence.",
      packageDir,
      count: entries.length,
      viewers,
      entries,
    },
    null,
    2,
  ),
);

await fs.writeFile(checklistPath, renderChecklist(entries));

console.log(
  JSON.stringify({
    ok: true,
    packageDir,
    count: entries.length,
    manifestPath,
    checklistPath,
    claimBoundary: "manual package generated; viewer pass/fail remains pending until recorded by app",
  }),
);

function selectRepresentativeFiles(files, count) {
  const byCategory = new Map();
  for (const file of files) {
    const category = extractCategory(file);
    const bucket = byCategory.get(category) ?? [];
    bucket.push(file);
    byCategory.set(category, bucket);
  }

  const selected = [];
  for (const bucket of byCategory.values()) {
    if (bucket[0]) {
      selected.push(bucket[0]);
    }
  }

  for (const file of files) {
    if (selected.length >= count) {
      break;
    }
    if (!selected.includes(file)) {
      selected.push(file);
    }
  }

  return selected.slice(0, count).sort();
}

function extractCategory(file) {
  const withoutExt = file.replace(/\.pdf$/i, "");
  const parts = withoutExt.split("-");
  return parts.slice(3).join("-");
}

function renderChecklist(entries) {
  const lines = [
    "# Manual Compatibility Smoke Package",
    "",
    "This checklist is generated by `npm run test:manual-smoke-package`.",
    "Rows are pending until the file is opened in the named viewer and the actual visual result is recorded.",
    "",
    `Package path: \`${packageDir}\``,
    "",
    "| ID | File | Category | Acrobat Pro/Reader | Preview | Chrome | Edge | Notes |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const entry of entries) {
    lines.push(
      `| ${entry.id} | \`${entry.file}\` | ${entry.category} | Pending | Pending | Pending | Pending | |`,
    );
  }
  lines.push("");
  lines.push("Do not convert Pending to Pass without a viewer-specific open/render/search/form/signature check.");
  lines.push("");
  return `${lines.join("\n")}\n`;
}
